export function getGradingColor(grading: HadithGrading): string {
  switch (grading) {
    case "Sahih": return "#22c55e";
    case "Hasan": return "#f59e0b";
    case "Hasan li Ghairihi": return "#f97316";
    case "Sahih li Ghairihi": return "#10b981";
    case "Mutawatir": return "#06b6d4";
    case "Mawquf": return "#8b5cf6";
    case "Da'if": return "#ef4444";
    default: return "#6b7280";
  }
}

export function getGradingLabel(grading: HadithGrading): string {
  switch (grading) {
    case "Sahih": return "Authentic";
    case "Hasan": return "Good";
    case "Hasan li Ghairihi": return "Good (by support)";
    case "Sahih li Ghairihi": return "Authentic (by support)";
    case "Mutawatir": return "Mass-transmitted";
    case "Mawquf": return "Companion-level";
    case "Da'if": return "Weak";
    default: return grading;
  }
}
